-- Watch reward: ignore client minutes/episode flags. 1 minute per eligible call.
-- Global 60s cooldown + 5 minute per-slug cooldown + 240 minutes/day.
create or replace function public.roflix_award_watch(
  p_movie_slug text,
  p_minutes integer default 0,
  p_episode boolean default false
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  u uuid := auth.uid();
  g public.roflix_game_stats;
  gain integer := 1;
  claimed_today integer;
  new_level integer;
  slug text;
begin
  if u is null then raise exception 'Login required'; end if;
  slug := left(trim(coalesce(p_movie_slug, '')), 180);
  if slug = '' then raise exception 'Movie slug required'; end if;
  if slug !~ '^[A-Za-z0-9][A-Za-z0-9._:-]{1,179}$' then
    return jsonb_build_object('awarded', false, 'reason', 'Invalid movie slug');
  end if;
  if exists (
    select 1 from public.roflix_watch_reward_claims
    where user_id = u and claimed_at > now() - interval '60 seconds'
  ) then
    return jsonb_build_object('awarded', false, 'reason', 'Global watch reward cooldown');
  end if;
  if exists (
    select 1 from public.roflix_watch_reward_claims
    where user_id = u and movie_slug = slug and claimed_at > now() - interval '5 minutes'
  ) then
    return jsonb_build_object('awarded', false, 'reason', 'Watch reward cooldown');
  end if;
  select coalesce(sum(claimed_minutes), 0)::integer
    into claimed_today
    from public.roflix_watch_reward_claims
    where user_id = u and claimed_at >= date_trunc('day', now());
  if claimed_today >= 240 then
    return jsonb_build_object('awarded', false, 'reason', 'Daily watch reward limit reached');
  end if;
  insert into public.roflix_game_stats(user_id) values (u) on conflict (user_id) do nothing;
  insert into public.roflix_watch_reward_claims(user_id, movie_slug, claimed_minutes, claim_bucket)
    values (u, slug, gain, date_trunc('minute', now()))
    on conflict (user_id, claim_bucket) do nothing;
  if not found then
    return jsonb_build_object('awarded', false, 'reason', 'Watch reward cooldown');
  end if;
  update public.roflix_game_stats
    set exp = coalesce(exp, 0) + 2,
        watch_minutes = coalesce(watch_minutes, 0) + gain,
        updated_at = now()
    where user_id = u
    returning * into g;
  new_level := greatest(1, floor(coalesce(g.exp, 0) / 1000) + 1)::int;
  update public.roflix_game_stats
    set level = new_level, updated_at = now()
    where user_id = u
    returning * into g;
  return jsonb_build_object(
    'awarded', true,
    'level', g.level,
    'exp', g.exp,
    'watch_minutes', g.watch_minutes,
    'awarded_minutes', gain
  );
end;
$$;

-- Legacy wallet RPC: never mutates. Returns current server gems so old clients resync.
create or replace function public.roflix_user_adjust_gem(p_delta bigint)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare g bigint;
begin
  if auth.uid() is null then raise exception 'Login required'; end if;
  insert into public.roflix_game_stats(user_id) values (auth.uid()) on conflict (user_id) do nothing;
  select coalesce(gems, 0) into g from public.roflix_game_stats where user_id = auth.uid();
  return jsonb_build_object('gems', g, 'mutated', false, 'ignored_delta', coalesce(p_delta, 0));
end;
$$;

