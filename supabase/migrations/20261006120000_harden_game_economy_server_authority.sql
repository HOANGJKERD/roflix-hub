create or replace function public.roflix_gacha_commit_batch(p_cost bigint, p_cards jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare n integer;
begin
  if jsonb_typeof(coalesce(p_cards, '[]'::jsonb)) <> 'array' then
    raise exception 'Invalid card batch';
  end if;
  n := jsonb_array_length(p_cards);
  if n not in (1, 10) then raise exception 'Invalid Gacha count'; end if;
  return public.roflix_gacha_roll(n);
end;
$$;

